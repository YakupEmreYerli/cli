// newDocsCmd regenerates the reference documentation from the command tree.
// It is hidden: maintainers run it via `make docs`.
func (a *App) newDocsCmd() *cobra.Command {
	var dir string
	cmd := &cobra.Command{
		Use:    "gen-docs",
		Short:  "Generate the command reference, enum list and skill file",
		Hidden: true,
		Args:   cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			root := cmd.Root()
			refDir := filepath.Join(dir, "docs", "reference")
			if err := os.MkdirAll(refDir, 0o755); err != nil {
				return err
			}
			files := map[string]string{
				filepath.Join(refDir, "README.md"):              referenceIndex(root),
				filepath.Join(dir, "docs", "enums.md"):          enumsDoc(),
				filepath.Join(dir, "skills", "dna", "SKILL.md"): SkillFile(),
			}
			for _, group := range sortedGroupNames() {
				for _, c := range root.Commands() {
					if c.Name() == group {
						files[filepath.Join(refDir, group+".md")] = groupDoc(c)
					}
				}
			}
			files[filepath.Join(refDir, "cli.md")] = cliCommandsDoc(root)
			for path, content := range files {
				if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
					return err
				}
				if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
					return err
				}
				fmt.Fprintln(a.Err, "wrote", path)
			}
			return nil
		},
	}
	cmd.Flags().StringVar(&dir, "dir", ".", "Repository root")
	return cmd
}

const generatedNote = "<!-- Generated by `make docs` (dna gen-docs). Do not edit by hand. -->\n\n"

func referenceIndex(root *cobra.Command) string {
	var b strings.Builder
	b.WriteString(generatedNote + "# Command reference\n\n")
	b.WriteString("Every API command, grouped as in the CLI. Safety: `read` (no side effects), `write` (changes data, free), " +
		"`destructive` (deletes or hard to undo, needs `--yes`), `billable` (charges balance, needs `--yes`).\n\n")
	b.WriteString("Global flags are listed in [cli.md](cli.md#global-flags).\n\n")
	groups := ops.Groups()
	for _, g := range sortedGroupNames() {
		fmt.Fprintf(&b, "## [%s](%s.md)\n\n%s.\n\n| command | safety | summary |\n|---|---|---|\n", g, g, groups[g])
		for _, op := range ops.All() {
			if op.CommandPath()[0] != g {
				continue
			}
			name := strings.Join(op.CommandPath(), " ")
			fmt.Fprintf(&b, "| [`dna %s`](%s.md#%s) | %s | %s |\n", name, g, anchor("dna "+name), op.Safety, op.Summary)
		}
		b.WriteString("\n")
	}
	b.WriteString("## [CLI commands](cli.md)\n\n`auth`, `config`, `api`, `schema`, `enums`, `agent`, `mcp`, `doctor`, `version`, `completion`.\n")
	return b.String()
}

func anchor(s string) string {
	s = strings.ToLower(s)
	var sb strings.Builder
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '-':
			sb.WriteRune(r)
		case r == ' ':
			sb.WriteByte('-')
		}
	}
	return sb.String()
}

func groupDoc(group *cobra.Command) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s# dna %s\n\n%s.\n\n", generatedNote, group.Name(), group.Short)
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		for _, sub := range c.Commands() {
			if sub.Hidden {
				continue
			}
			if _, isOp := sub.Annotations["operation"]; isOp {
				b.WriteString(commandDoc(sub))
				continue
			}
			walk(sub)
		}
	}
	walk(group)
	return b.String()
}

func commandDoc(c *cobra.Command) string {
	var b strings.Builder
	fmt.Fprintf(&b, "## %s\n\n", c.CommandPath())
	fmt.Fprintf(&b, "```\n%s\n```\n\n", c.UseLine())
	b.WriteString(markdownLong(c.Long) + "\n\n")
	if len(c.Aliases) > 0 {
		fmt.Fprintf(&b, "Aliases: `%s`\n\n", strings.Join(c.Aliases, "`, `"))
	}
	b.WriteString(flagTable(c.LocalFlags()))
	if c.Example != "" {
		fmt.Fprintf(&b, "**Examples**\n\n```bash\n%s\n```\n\n", strings.TrimRight(dedent(c.Example), "\n"))
	}
	return b.String()
}

// markdownLong turns the "Key: value" block of op help into a list.
func markdownLong(long string) string {
	var out []string
	for _, line := range strings.Split(long, "\n") {
		for _, key := range []string{"Safety:", "API:", "Body:", "Returns:", "Schema:"} {
			if strings.HasPrefix(line, key) {
				val := strings.TrimSpace(strings.TrimPrefix(line, key))
				line = "- **" + strings.TrimSuffix(key, ":") + ":** " + backtickCode(key, val)
			}
		}
		out = append(out, line)
	}
	return strings.Join(out, "\n")
}

func backtickCode(key, val string) string {
	switch key {
	case "API:", "Body:", "Returns:":
		if strings.HasPrefix(val, "nothing") {
			return val
		}
		return "`" + val + "`"
	case "Schema:":
		parts := strings.SplitN(val, "(", 2)
		s := "`" + strings.TrimSpace(parts[0]) + "`"
		if len(parts) == 2 {
			s += " (" + strings.ReplaceAll(strings.TrimSuffix(parts[1], ")"), "MCP tool: ", "MCP tool: `") + "`)"
		}
		return s
	}
	return val
}

func dedent(s string) string {
	lines := strings.Split(s, "\n")
	for i, l := range lines {
		lines[i] = strings.TrimPrefix(l, "  ")
	}
	return strings.Join(lines, "\n")
}

func flagTable(fs *pflag.FlagSet) string {
	var rows []string
	fs.VisitAll(func(f *pflag.Flag) {
		if f.Hidden {
			return
		}
		name := "`--" + f.Name + "`"
		if f.Shorthand != "" {
			name = "`-" + f.Shorthand + "`, " + name
		}
		typ := f.Value.Type()
		switch typ {
		case "stringArray":
			typ = "strings"
		case "bool":
			typ = ""
		}
		usage := strings.NewReplacer("|", "\\|", "<", "&lt;", ">", "&gt;").Replace(f.Usage)
		rows = append(rows, fmt.Sprintf("| %s | %s | %s |", name, typ, usage))
	})
	if len(rows) == 0 {
		return ""
	}
	return "| flag | type | description |\n|---|---|---|\n" + strings.Join(rows, "\n") + "\n\n"
}

func cliCommandsDoc(root *cobra.Command) string {
	var b strings.Builder
	b.WriteString(generatedNote + "# CLI commands\n\nCommands that configure the CLI or help tools and AI agents. API commands are in the [index](README.md).\n\n")
	b.WriteString("## Global flags\n\nThese work with every command.\n\n")
	b.WriteString(flagTable(root.PersistentFlags()))
	var names []string
	byName := map[string]*cobra.Command{}
	for _, c := range root.Commands() {
		if c.GroupID == "cli" && !c.Hidden {
			names = append(names, c.Name())
			byName[c.Name()] = c
		}
	}
	sort.Strings(names)
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		fmt.Fprintf(&b, "## %s\n\n%s\n\n", c.CommandPath(), firstNonEmpty(c.Long, c.Short))
		if c.Runnable() {
			fmt.Fprintf(&b, "```\n%s\n```\n\n", c.UseLine())
			b.WriteString(flagTable(c.LocalNonPersistentFlags()))
		}
		if c.Example != "" {
			fmt.Fprintf(&b, "**Examples**\n\n```bash\n%s\n```\n\n", strings.TrimRight(dedent(c.Example), "\n"))
		}
		for _, sub := range c.Commands() {
			if !sub.Hidden && sub.Name() != "help" {
				walk(sub)
			}
		}
	}
	for _, n := range names {
		walk(byName[n])
	}
	return b.String()
}

func firstNonEmpty(s ...string) string {
	for _, x := range s {
		if strings.TrimSpace(x) != "" {
			return x
		}
	}
	return ""
}

func enumsDoc() string {
	var b strings.Builder
	b.WriteString(generatedNote + "# Enums\n\nThe API sends these fields as numbers (or accepts only these words). " +
		"Flags and MCP tools accept the names as well; `dna enums <Name>` prints the same list.\n\n")
	for _, e := range dna.Enums() {
		fmt.Fprintf(&b, "## %s\n\n%s\n\n", e.Name, e.Description)
		if e.Kind == "string" {
			b.WriteString("| value | meaning |\n|---|---|\n")
			for _, v := range e.Values {
				fmt.Fprintf(&b, "| `%s` | %s |\n", v.Name, v.Description)
			}
		} else {
			b.WriteString("| value | name | meaning |\n|---:|---|---|\n")
			for _, v := range e.Values {
				fmt.Fprintf(&b, "| %v | `%s` | %s |\n", v.Value, v.Name, v.Description)
			}
		}
		b.WriteString("\n")
	}
	return b.String()
}
